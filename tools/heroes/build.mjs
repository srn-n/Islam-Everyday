// Builds assets/heroes.js from tools/heroes/source.mjs and data/quran. Run: node tools/heroes/build.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { PRAYER, HADITH_HERO, QURAN } from "./source.mjs";
const root = new URL("../../", import.meta.url);
const load = (l, s) => { const j = JSON.parse(readFileSync(new URL(`data/quran/${l}/${String(s).padStart(3, "0")}.json`, root), "utf8")); return Array.isArray(j) ? j : j.t; };
const item = x => {
  if (x.h) return { k: "h", ref: { en: x.h.ref, bn: x.h.refBn }, url: x.h.url, en: x.h.en, bn: x.h.bn, g: x.h.g };
  const [s, a, b] = x.q, en = load("en", s), bn = load("bn", s), ar = load("ar", s), pick = t => { const o = []; for (let k = a; k <= b; k++) { if (t[k - 1] == null) throw new Error(`missing ${s}:${k}`); o.push(t[k - 1]); } return o; };
  return { k: "q", s, a, b, ar: pick(ar), en: pick(en), bn: pick(bn) };
};
const out = { PRAYER: Object.fromEntries(Object.entries(PRAYER).map(([k, v]) => [k, v.map(item)])), HADITH_HERO: item({ h: HADITH_HERO }), QURAN: QURAN.map(item) };
for (const [k, v] of Object.entries(out.PRAYER)) if (v.length < 3 || v.length > 7) throw new Error(`${k}: ${v.length} entries (3 to 7 wanted)`);
if (out.QURAN.length < 15) throw new Error("Qur'an hero needs at least 15");
const js = `/* Islam Everyday — verses and hadiths for the Today, Hadith and Qur'an heroes and the reminders (Nov 2026).
 * GENERATED by tools/heroes/build.mjs from tools/heroes/source.mjs — do not edit by hand.
 * Qur'an (k:"q"): Arabic, English (Pickthall) and Bangla (Dr. Abu Bakr Muhammad Zakaria) copied unchanged from
 * data/quran, including the translator's footnote markers. Hadith (k:"h"): the meaning in plain words written for
 * this app from the Arabic at the reference; not a published translation and not reviewed by a scholar. */
(function (root, factory) { const api = factory(); if (typeof module === "object" && module.exports) module.exports = api; else root.IE_HEROES = api; })(typeof self !== "undefined" ? self : this, function () {
  "use strict";
  const D = ${JSON.stringify(out)};
  /* Whole days since 1 Jan 1970 for a calendar date; weeks begin on Thursday (1 Jan 1970 was one). */
  const dayNo = (y, m, d) => Math.floor(Date.UTC(y, m - 1, d) / 864e5), weekNo = n => Math.floor(n / 7);
  const forPrayer = (k, n) => { const L = D.PRAYER[k] || []; return L.length ? L[((k === "jumuah" ? weekNo(n) : n) % L.length + L.length) % L.length] : null; };
  const forWeek = n => D.QURAN[(weekNo(n) % D.QURAN.length + D.QURAN.length) % D.QURAN.length];
  return { PRAYER: D.PRAYER, HADITH_HERO: D.HADITH_HERO, QURAN: D.QURAN, dayNo, weekNo, forPrayer, forWeek };
});
`;
writeFileSync(new URL("assets/heroes.js", root), js);
console.log("assets/heroes.js", js.length, "bytes");
