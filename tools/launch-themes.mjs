// Launch screen colours for every theme pair (Nov 2026, 14th, owner's request: "the opening boot-up colour the same").
// Android 13+ lets the app pick the launch screen theme of the NEXT start (SplashScreen.setSplashScreenTheme). The app
// has three light themes and three dark ones, and the phone (or the app's own Light/Dark choice) decides which one shows,
// so there is one launch theme per pair (light x dark = 9), whose colours switch with night mode (values / values-night):
// the ground colour behind the doorway and the doorway's accent colour, read here from assets/app.css so they always
// equal what the page paints. Writes:
//   res/values/launch_colors.xml, res/values-night/launch_colors.xml   lg_<light>_<dark>, la_<light>_<dark>
//   res/drawable/splash_door_<light>_<dark>.xml                          the doorway in that pair's accent
//   res/values-v31/launch_themes.xml                                     Launch.<light>.<dark> styles
// and prints the Java colour table used by AppearancePlugin (checked by tests/launch.test.mjs).
// Run: node tools/launch-themes.mjs
import { readFileSync, writeFileSync } from "node:fs";
const root = new URL("../", import.meta.url), R = new URL("android-app/android/app/src/main/res/", root);
const css = readFileSync(new URL("assets/app.css", root), "utf8");
const block = sel => { const i = css.indexOf(sel + "{"); if (i < 0) throw new Error("no " + sel); return css.slice(i, css.indexOf("}", i)); };
const v = (b, k) => { const m = b.match(new RegExp("--" + k + ":(#[0-9A-Fa-f]{6})")); if (!m) throw new Error(k); return m[1].toUpperCase(); };
const SEL = {
  classic: ":root", sky: ':root[data-palette="sky"]', sandstone: ':root[data-palette="sandstone"]',
  jade: ':root[data-theme="dark"]', indigo: ':root[data-palette="indigo"][data-theme="dark"]', teal: ':root[data-palette="teal"][data-theme="dark"]'
};
export const LIGHT = ["classic", "sky", "sandstone"], DARK = ["jade", "indigo", "teal"];
export const COL = Object.fromEntries(Object.entries(SEL).map(([k, s]) => { const b = block(s); return [k, { g: v(b, "ground"), a: v(b, "accent") }]; }));
const head = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/launch-themes.mjs from assets/app.css; do not edit by hand. -->\n<resources>\n';
let day = head, night = head, styles = head.replace("<resources>", "<resources>\n    <!-- Android 13+: the launch screen of the next start, chosen by AppearancePlugin.splashTheme(). -->");
for (const l of LIGHT) for (const d of DARK) {
  const n = l + "_" + d;
  day += `    <color name="lg_${n}">${COL[l].g}</color>\n    <color name="la_${n}">${COL[l].a}</color>\n`;
  night += `    <color name="lg_${n}">${COL[d].g}</color>\n    <color name="la_${n}">${COL[d].a}</color>\n`;
  styles += `    <style name="Launch.${l[0].toUpperCase() + l.slice(1)}.${d[0].toUpperCase() + d.slice(1)}" parent="AppTheme.NoActionBarLaunch">
        <item name="windowSplashScreenBackground">@color/lg_${n}</item>
        <item name="windowSplashScreenAnimatedIcon">@drawable/splash_door_${n}</item>
        <item name="android:windowSplashScreenBackground">@color/lg_${n}</item>
        <item name="android:windowSplashScreenAnimatedIcon">@drawable/splash_door_${n}</item>
        <item name="android:windowBackground">@color/lg_${n}</item>
    </style>\n`;
  const door = readFileSync(new URL("drawable/splash_door.xml", R), "utf8").replace(/@color\/launch_accent/g, "@color/la_" + n)
    .replace(/<!--[\s\S]*?-->\n/, `<!-- Generated by tools/launch-themes.mjs: the launch doorway (drawable/splash_door.xml) in the ${l} / ${d} accent. -->\n`);
  writeFileSync(new URL(`drawable/splash_door_${n}.xml`, R), door);
}
writeFileSync(new URL("values/launch_colors.xml", R), day + "</resources>\n");
writeFileSync(new URL("values-night/launch_colors.xml", R), night + "</resources>\n");
writeFileSync(new URL("values-v31/launch_themes.xml", R), styles + "</resources>\n");
console.log(JSON.stringify(COL));
