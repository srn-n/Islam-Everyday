#!/usr/bin/env python3
"""Build assets/name-stories.js from tools/name-stories/stories_*.py (Face 7.2).
Each of the 99 Names gets one everyday story in English and Bangla, written for this app as a teaching example.
Checks: every id exists in assets/names.js, all 99 are present, both languages are non-empty, and dialogue quotes are
balanced. Straight double quotes are turned into curly ones."""
import glob, importlib.util, json, os, re, subprocess
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ids = json.loads(subprocess.check_output(['node', '-e', '''
const vm=require("vm"),c={self:{}};vm.runInNewContext(require("fs").readFileSync(process.argv[1],"utf8"),c);
console.log(JSON.stringify(c.self.DINSATHI_NAMES.names.map(x=>x.id)));''', os.path.join(ROOT, 'assets/names.js')]))
N = {}
for f in sorted(glob.glob(os.path.join(ROOT, 'tools/name-stories/stories_*.py'))):
    sp = importlib.util.spec_from_file_location('m', f); m = importlib.util.module_from_spec(sp); sp.loader.exec_module(m)
    for k in m.N: assert k not in N, 'duplicate ' + k
    N.update(m.N)
def curly(t):
    out, op = [], True
    for ch in t:
        if ch == '"': out.append('“' if op else '”'); op = not op
        else: out.append(ch)
    t = ''.join(out)
    q = ''.join(c for c in t if c in '“”')
    assert q == '“”' * (len(q) // 2), 'unbalanced quotes: ' + t[:80]
    return t
probs = [k for k in N if k not in ids] + ['missing ' + k for k in ids if k not in N]
out = {}
for k in ids:
    if k not in N: continue
    en, bn = N[k]
    assert en.strip() and bn.strip(), k
    out[k] = {"en": [curly(p.strip()) for p in en.strip().split('\n\n')], "bn": [curly(p.strip()) for p in bn.strip().split('\n\n')]}
if probs:
    print('\n'.join(probs[:5]), '...' if len(probs) > 5 else '')
    if os.environ.get('STRICT') or any(not p.startswith('missing') for p in probs): raise SystemExit(1)
js = """/* Islam Everyday — 99 Names: an everyday story for each name (Face 7.2). GENERATED by tools/name-stories/build.py
 * from tools/name-stories/stories_*.py; edit those files, not this one.
 * Each story is an illustration written for this app with an AI assistant, to help a reader relate the meaning in the
 * name's sourced explanation to ordinary life. It is not a source-based claim, tafsir or a ruling, and no human quality
 * in a story is a measure of Allah's. review: "draft" — not yet reviewed by a qualified scholar. */
(function (root) {
  const S = """ + json.dumps(out, ensure_ascii=False, indent=0) + """;
  const api = { review: "draft", get: id => S[id] || null, count: Object.keys(S).length };
  if (typeof module === "object" && module.exports) module.exports = api; else root.IE_NAME_STORIES = api;
})(typeof self !== "undefined" ? self : this);
"""
open(os.path.join(ROOT, 'assets/name-stories.js'), 'w', encoding='utf8').write(js)
print('ok', len(out), 'of 99 name stories,', len(js), 'bytes')
