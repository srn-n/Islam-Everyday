// Builds assets/share.js from tools/share/source.mjs (17 Nov 2026):
//   node tools/share/build.mjs <english_rwwad.sqlite>
// Arabic and Bangla (Dr. Abu Bakr Muhammad Zakaria) are copied unchanged from data/quran; English is the Rowwad
// Translation Center's (QuranEnc), read unchanged from QuranEnc's own sqlite (the same file and version as
// assets/en-rwwad.js, checked below). Loaded only when a tracker picture is made, so the first screen stays small.
import { readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import vm from "node:vm";
import { TRACK } from "./source.mjs";
const root = new URL("../../", import.meta.url), rd = f => readFileSync(new URL(f, root), "utf8"), db = process.argv[2];
if (!db) throw new Error("usage: node tools/share/build.mjs <english_rwwad.sqlite>");
const c = { self: {}, window: {} }; c.self = c; c.window = c; vm.createContext(c); vm.runInContext(rd("assets/en-rwwad.js"), c);
const sha = createHash("sha256").update(readFileSync(db)).digest("hex");
if (!rd("assets/en-rwwad.js").includes(sha)) throw new Error("this sqlite is not the one assets/en-rwwad.js was made from");
const load = (l, s) => { const j = JSON.parse(rd(`data/quran/${l}/${String(s).padStart(3, "0")}.json`)); return Array.isArray(j) ? j : j.t; };
const rw = (s, a) => JSON.parse(execFileSync("python3", ["-c", `import sqlite3,json,sys;r=sqlite3.connect(sys.argv[1]).execute('select translation from translations where sura=? and aya=?',(int(sys.argv[2]),int(sys.argv[3]))).fetchone();print(json.dumps(r[0] if r else None))`, db, String(s), String(a)], { encoding: "utf8" }));
const out = TRACK.map(({ q: [s, a, b] }) => {
  const ar = load("ar", s), bn = load("bn", s), o = { k: "q", s, a, b, ar: [], en: [], bn: [] };
  for (let k = a; k <= b; k++) { const e = rw(s, k); if (!e || ar[k - 1] == null || bn[k - 1] == null) throw new Error(`missing ${s}:${k}`); o.ar.push(ar[k - 1]); o.en.push(e); o.bn.push(bn[k - 1]); }
  return o;
});
writeFileSync(new URL("assets/share.js", root), `/* Islam Everyday — the verse printed on a shared prayer-tracker picture (17 Nov 2026).
 * GENERATED by tools/share/build.mjs from tools/share/source.mjs — do not edit by hand.
 * Arabic and Bangla (Dr. Abu Bakr Muhammad Zakaria) unchanged from data/quran; English from the Rowwad Translation
 * Center (QuranEnc, version ${c.IE_RWWAD.META.version}), unchanged with its footnote markers (the app hides them). Not reviewed by a scholar. */
(function (root, factory) { const api = factory(); if (typeof module === "object" && module.exports) module.exports = api; else root.IE_SHARE = api; })(typeof self !== "undefined" ? self : this, function () {
  "use strict";
  const TRACK = ${JSON.stringify(out)};
  /* The verse of a day: the list turns with the day number. */
  const trackFor = n => TRACK[((n % TRACK.length) + TRACK.length) % TRACK.length];
  return { TRACK, trackFor };
});
`);
console.log("assets/share.js:", out.length, "verses");
