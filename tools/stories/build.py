#!/usr/bin/env python3
"""Build assets/stories.js from tools/stories/stories_*.py (Face 7.1 Qur'an Stories).
Checks: unique ids, known groups and source kinds, every Qur'an reference exists (verse counts from data/quran/en),
hadith entries carry a sunnah.com link, and every text has English and Bangla."""
import glob, importlib.util, json, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
S = []
for f in sorted(glob.glob(os.path.join(ROOT, 'tools/stories/stories_*.py'))):
    sp = importlib.util.spec_from_file_location('m', f); m = importlib.util.module_from_spec(sp); sp.loader.exec_module(m); S += m.S
# Face 7.2: the complete retelling of each story ("The story"), from tools/stories/narr_*.py.
NARR = {}
for f in sorted(glob.glob(os.path.join(ROOT, 'tools/stories/narr_*.py'))):
    sp = importlib.util.spec_from_file_location('n', f); m = importlib.util.module_from_spec(sp); sp.loader.exec_module(m); NARR.update(m.N)
GROUPS = [["prophets", "Prophets and messengers", "নবী ও রাসূল"], ["peoples", "People and communities in the Qur'an", "কুরআনে বর্ণিত মানুষ ও জাতি"], ["hadith", "Stories the Prophet ﷺ told", "নবী ﷺ-এর বর্ণিত কাহিনি"], ["companions", "Lives of the Companions", "সাহাবিদের জীবন"]]
KINDS = {"quran", "hadith", "tafsir"}
cnt = lambda n: len(json.load(open(os.path.join(ROOT, f'data/quran/en/{n:03d}.json'))))
probs = []; ids = set(); out = []
for s in S:
    assert s['id'] not in ids, s['id']; ids.add(s['id'])
    assert s['group'] in [g[0] for g in GROUPS], s['id']
    for k in ('title', 'short', 'unknown', 'why', 'example'):
        assert len(s[k]) == 2 and all(x.strip() for x in s[k]), (s['id'], k)
    parts = []
    for kind, refs, en, bn in s['parts']:
        assert kind in KINDS and en.strip() and bn.strip(), (s['id'], kind)
        rl = []
        if kind != 'hadith':
            for r in re.split(r';\s*', refs):
                m = re.fullmatch(r'(\d+):(\d+)(?:[–-](\d+))?', r.strip())
                if not m: probs.append(f"{s['id']}: bad ref {r}"); continue
                n, a, b = int(m[1]), int(m[2]), int(m[3] or m[2])
                if not (1 <= a <= b <= cnt(n)): probs.append(f"{s['id']}: {r} out of range")
                rl.append(r.strip())
        else:
            rl = [r.strip() for r in refs.split(';')]
        parts.append({"kind": kind, "refs": rl, "text": {"en": en, "bn": bn}})
    # The complete retelling: required for every story; double-quoted words must be copied exactly from its parts.
    if s['id'] not in NARR: probs.append(f"{s['id']}: no complete retelling in narr_*.py")
    else:
        ne, nb = NARR[s['id']]
        assert ne.strip() and nb.strip(), s['id']
        for txt, src in ((ne, ' '.join(p['text']['en'] for p in parts)), (nb, ' '.join(p['text']['bn'] for p in parts))):
            for q in re.findall(r'“([^”]+)”', txt):
                if q not in src: probs.append(f"{s['id']}: quoted words not found in the story's parts: {q[:60]}")
    if any(p['kind'] == 'hadith' for p in parts):
        assert s.get('hadith'), (s['id'], 'hadith links')
        for lab, url, grade in s['hadith']:
            assert url.startswith('https://sunnah.com/'), url
    out.append({"id": s['id'], "group": s['group'], "title": {"en": s['title'][0], "bn": s['title'][1]}, "short": {"en": s['short'][0], "bn": s['short'][1]},
                "story": {"en": [x.strip() for x in NARR.get(s['id'], ("", ""))[0].strip().split("\n\n")], "bn": [x.strip() for x in NARR.get(s['id'], ("", ""))[1].strip().split("\n\n")]},
                "parts": parts, "hadith": [{"label": a, "url": b, "grade": c} for a, b, c in s.get('hadith', [])],
                "unknown": {"en": s['unknown'][0], "bn": s['unknown'][1]}, "why": {"en": s['why'][0], "bn": s['why'][1]},
                "example": {"en": s['example'][0], "bn": s['example'][1]}, "review": "draft"})
if probs: print('\n'.join(probs)); raise SystemExit(1)
js = """/* Islam Everyday — Qur'an Stories (Face 7.1; complete retellings and new stories in Face 7.2). GENERATED by tools/stories/build.py from tools/stories/stories_*.py;
 * edit those files, not this one.
 *
 * A data-driven catalogue: more stories can be added as new entries. Every part of a story carries its source type:
 *   "quran"  — a retelling of what the cited verses say (checked against the Rowwad English and Zakaria Bangla),
 *   "hadith" — a retelling of a narration in Sahih al-Bukhari / Sahih Muslim (references checked on sunnah.com),
 *   "tafsir" — a point taken from Al-Mukhtasar, the tafsir bundled with the app's reader.
 * "story" is the complete retelling (paragraphs), joining the parts into one account without adding to them; the
 * parts are shown under it as the references.
 * "unknown" lists what the sources do not say, so popular details are not presented as fact. "why" and "example" are
 * the app's own reflections; the examples are modern analogies written for learning, not source text or rulings.
 * Words in double quotation marks are exact quotations from a named translation; single quotation marks are the
 * app's wording. Retellings are the app's own words, drafted with an AI assistant. review: "draft" — NOT yet
 * reviewed by a qualified scholar.
 */
(function (root, factory) {
  const api = factory();
  if (typeof module === "object" && module.exports) module.exports = api;
  else root.IE_STORIES = api;
})(typeof self !== "undefined" ? self : this, function () {
  const GROUPS = """ + json.dumps(GROUPS, ensure_ascii=False) + """;
  const STORIES = """ + json.dumps(out, ensure_ascii=False, indent=0) + """;
  return { GROUPS, STORIES, review: "draft", get: id => STORIES.find(s => s.id === id) || null };
});
"""
open(os.path.join(ROOT, 'assets/stories.js'), 'w', encoding='utf8').write(js)
print('ok', len(out), 'stories', {g[0]: sum(1 for s in out if s['group'] == g[0]) for g in GROUPS}, len(js), 'bytes')
