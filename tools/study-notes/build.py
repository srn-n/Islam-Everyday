#!/usr/bin/env python3
"""Build assets/study-notes.js from tools/study-notes/notes_*.py (Face 7.1).
Checks every surah in assets/study.js has notes, that flow ranges cover the surah in order without gaps or overlaps,
and that every concept reference points at verses that exist (verse counts from data/quran/en/NNN.json)."""
import glob, importlib.util, json, os, re, subprocess
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
N = {}
for f in sorted(glob.glob(os.path.join(ROOT, 'tools/study-notes/notes_*.py'))):
    sp = importlib.util.spec_from_file_location('m', f); m = importlib.util.module_from_spec(sp); sp.loader.exec_module(m)
    for k, v in m.N.items():
        assert k not in N, f'duplicate {k}'; N[k] = v
want = json.loads(subprocess.check_output(['node', '-e', "const fs=require('fs'),c={};c.self=c;new Function('self','module',fs.readFileSync(process.argv[1]+'/assets/study.js','utf8'))(c,undefined);console.log(JSON.stringify(c.IE_STUDY.SURAHS.map(s=>s.n)))", ROOT]))
assert sorted(N) == sorted(want), (set(want) - set(N), set(N) - set(want))
problems = []
def count(n): return len(json.load(open(os.path.join(ROOT, f'data/quran/en/{n:03d}.json'))))
def refs(r):
    out = []
    for part in re.split(r'[;,]\s*', r):
        m = re.fullmatch(r'(\d+):(\d+)(?:[–-](\d+))?', part.strip())
        if not m: problems.append(f'bad ref {r}'); continue
        out.append((int(m[1]), int(m[2]), int(m[3] or m[2])))
    return out
out = {}
for n in sorted(N):
    e = N[n]; c = count(n)
    for key in ('short', 'ov', 'flow', 'concepts', 'take', 'example'):
        assert key in e, f'{n} missing {key}'
    pos = 1
    for a, b, en, bn in e['flow']:
        if a != pos: problems.append(f'{n}: flow starts {a}, expected {pos}')
        if b < a or b > c: problems.append(f'{n}: flow {a}-{b} outside 1-{c}')
        pos = b + 1
    if pos != c + 1: problems.append(f'{n}: flow ends at {pos-1}, surah has {c}')
    for t in e['concepts']:
        assert len(t) == 6 and t[5] in ('q', 't', 'h'), (n, t[0])
        for s, a, b in refs(t[4]):
            cc = count(s)
            if not (1 <= a <= b <= cc): problems.append(f'{n}: concept ref {t[4]} outside {s}:1-{cc}')
    assert len(e['take'][0]) == len(e['take'][1]) >= 3, (n, 'take')
    out[n] = {"short": {"en": e['short'][0], "bn": e['short'][1]}, "ov": {"en": e['ov'][0], "bn": e['ov'][1]},
              "flow": [[a, b, {"en": en, "bn": bn}] for a, b, en, bn in e['flow']],
              "concepts": [{"term": {"en": t[0], "bn": t[1]}, "text": {"en": t[2], "bn": t[3]}, "ref": t[4], "src": t[5]} for t in e['concepts']],
              "take": {"en": e['take'][0], "bn": e['take'][1]}, "example": {"en": e['example'][0], "bn": e['example'][1]}}
if problems:
    print('\n'.join(problems)); raise SystemExit(1)
js = """/* Islam Everyday — Qur'an study notes (Face 7.1). GENERATED by tools/study-notes/build.py from
 * tools/study-notes/notes_*.py — edit those files, not this one.
 *
 * For each surah in the study library: a short preview, an overview, how the surah unfolds (verse ranges), key
 * concepts (src "q" = taken from the Qur'an's own wording, cited by verse; "t" = from Al-Mukhtasar, the tafsir
 * bundled in the app's reader, named as such), takeaways, and one modern-life example.
 * ALL of this is DRAFT editorial material written for the app with an AI assistant. It is not Qur'an text, not a
 * translation and not tafsir; the modern examples are illustrations created for learning, not rulings. It has NOT
 * been reviewed by a qualified scholar. No revelation dates, order, occasions, virtues or rewards are given.
 */
(function (root, factory) {
  const api = factory();
  if (typeof module === "object" && module.exports) module.exports = api;
  else root.IE_STUDY_NOTES = api;
})(typeof self !== "undefined" ? self : this, function () {
  const NOTES = """ + json.dumps(out, ensure_ascii=False, indent=0) + """;
  return { NOTES, review: "draft", get: n => NOTES[n] || null };
});
"""
open(os.path.join(ROOT, 'assets/study-notes.js'), 'w', encoding='utf8').write(js)
print('ok', len(out), 'surahs,', len(js), 'bytes')
