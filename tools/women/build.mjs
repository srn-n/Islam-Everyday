// Builds assets/women.js from tools/women/source.mjs (16 Nov 2026). Run: node tools/women/build.mjs
// Every text is copied unchanged from its source (Unicode NFC, as assets/hadith.js); nothing is written or edited here.
import { readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";
import { WELCOME, WORTH, DHIKR, DEEDS } from "./source.mjs";
import { I18N } from "./strings.mjs";
const root = new URL("../../", import.meta.url), rd = f => readFileSync(new URL(f, root), "utf8");
const browser = f => { const c = { self: {}, window: {} }; c.self = c; c.window = c; vm.createContext(c); vm.runInContext(rd(f), c); return c; };
const RW = browser("assets/en-rwwad.js").IE_RWWAD, LIB = browser("assets/hadith.js").IE_HADITH;
const load = (l, s) => { const j = JSON.parse(rd(`data/quran/${l}/${String(s).padStart(3, "0")}.json`)); return Array.isArray(j) ? j : j.t; };
const N = s => String(s).normalize("NFC");
const item = x => {
  if (x.q) {
    const [s, a, b] = x.q, ar = load("ar", s), bn = load("bn", s), en = [];
    for (let k = a; k <= b; k++) { const v = RW.get(s, k); if (!v) throw new Error(`Rowwad missing ${s}:${k}: re-run tools/import-rwwad-subset.py`); en.push(v[0]); }
    const pick = t => { const o = []; for (let k = a; k <= b; k++) { if (t[k - 1] == null) throw new Error(`missing ${s}:${k}`); o.push(t[k - 1]); } return o; };
    return { k: "q", s, a, b, ar: pick(ar), en, bn: pick(bn) };
  }
  if (x.he) {
    const r = l => JSON.parse(readFileSync(new URL(`tools/women/hadeethenc/${x.he}-${l}.json`, root), "utf8"));
    const en = r("en"), bn = r("bn"), ar = r("ar");
    if (!/Muslim|Bukhari/.test(en.attribution) || !/^Authentic/.test(en.grade)) throw new Error(`${x.he}: not Bukhari/Muslim authentic`);
    return { k: "h", id: "he" + x.he, ar: N(ar.hadeeth), en: N(en.hadeeth), bn: N(bn.hadeeth), att: { en: N(en.attribution), bn: N(bn.attribution) },
      grade: { en: N(en.grade), bn: N(bn.grade) }, refs: x.refs.map(([c, n, wording]) => ({ c, n, url: `https://sunnah.com/${c}:${n}`, wording })), src: `https://hadeethenc.com/en/browse/hadith/${x.he}` };
  }
  const h = LIB.HADITH.find(z => z.id === x.lib); if (!h) throw new Error("no library hadith " + x.lib);
  return { k: "h", id: h.id, ar: h.ar, en: h.en, bn: h.bn, att: h.attribution, grade: h.grade, refs: h.refs.map(r => ({ c: r.c, n: r.n, url: r.url, wording: r.wording })), src: h.source };
};
const out = { I18N, WELCOME: item(WELCOME), WORTH: WORTH.map(item), DHIKR: DHIKR.map(item), DEEDS: DEEDS.map(item) };
const used = new Set([...out.WORTH, ...out.DEEDS].filter(x => x.k === "q").map(x => x.s + ":" + x.a));
if (used.has(out.WELCOME.s + ":" + out.WELCOME.a)) throw new Error("the welcome verse must not be a reminder verse");
writeFileSync(new URL("assets/women.js", root), `/* Islam Everyday — texts for the For women page and the reminders on period days (16 Nov 2026).
 * GENERATED by tools/women/build.mjs from tools/women/source.mjs — do not edit by hand.
 * Qur'an (k:"q"): Arabic and Bangla (Dr. Abu Bakr Muhammad Zakaria) unchanged from data/quran; English from the
 * Rowwad Translation Center (QuranEnc, version ${RW.META.version}), unchanged with its footnote markers (the app hides them).
 * Hadith (k:"h"): Arabic, English and Bangla, attribution and grade unchanged from HadeethEnc.com (Sahih al-Bukhari or
 * Sahih Muslim, graded authentic); "he…" entries retrieved 16 Nov 2026 (tools/women/hadeethenc), "h…" entries are the
 * app's Hadith library (assets/hadith.js). Not reviewed by a scholar. */
(function (root, factory) { const api = factory(); if (typeof module === "object" && module.exports) module.exports = api; else root.IE_WOMEN = api; })(typeof self !== "undefined" ? self : this, function () {
  "use strict";
  const D = ${JSON.stringify(out)};
  const at = (L, n) => L[((n % L.length) + L.length) % L.length];
  /* The three reminders of a day: worth, remembrance, good deeds; each list turns with the day number. */
  const forDay = n => [at(D.WORTH, n), at(D.DHIKR, n), at(D.DEEDS, n)];
  return Object.assign({ forDay }, D);
});
`);
console.log("assets/women.js:", out.WORTH.length, "worth,", out.DHIKR.length, "dhikr,", out.DEEDS.length, "deeds");
